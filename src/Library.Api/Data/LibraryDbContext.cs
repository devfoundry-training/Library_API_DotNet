using Library.Api.Data.Entities;
using Microsoft.EntityFrameworkCore;

namespace Library.Api.Data;

/// <summary>
/// The EF Core context the repositories use. The model is the same for both databases; each
/// provider has its own subclass so it can keep its own migrations (Data/Migrations/Sqlite and
/// Data/Migrations/PostgreSql).
/// </summary>
public abstract class LibraryDbContext(DbContextOptions options) : DbContext(options)
{
    public DbSet<Book> Books => Set<Book>();
    public DbSet<Member> Members => Set<Member>();
    public DbSet<Loan> Loans => Set<Loan>();

    protected override void OnModelCreating(ModelBuilder modelBuilder) =>
        modelBuilder.ApplyConfigurationsFromAssembly(typeof(LibraryDbContext).Assembly);
}

/// <summary>
/// EF Core's SQLite provider declares the keys INTEGER PRIMARY KEY AUTOINCREMENT, so the id
/// counters live in sqlite_sequence and a reset clears them (see LibrarySeeder).
/// </summary>
public sealed class SqliteLibraryDbContext(DbContextOptions<SqliteLibraryDbContext> options)
    : LibraryDbContext(options);

/// <summary>
/// Npgsql makes int keys GENERATED BY DEFAULT AS IDENTITY, so the seed can still insert fixed ids.
/// </summary>
public sealed class PostgreSqlLibraryDbContext(DbContextOptions<PostgreSqlLibraryDbContext> options)
    : LibraryDbContext(options);
